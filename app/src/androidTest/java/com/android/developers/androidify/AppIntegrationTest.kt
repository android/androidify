package com.android.developers.androidify

import androidx.compose.material3.ExperimentalMaterial3ExpressiveApi
import androidx.compose.ui.test.junit4.v2.createAndroidComposeRule
import dagger.hilt.android.testing.HiltAndroidRule
import dagger.hilt.android.testing.HiltAndroidTest
import org.junit.Before
import org.junit.Rule
import org.junit.Test

@OptIn(ExperimentalMaterial3ExpressiveApi::class)
@HiltAndroidTest
class AppIntegrationTest {

    @get:Rule(order = 0)
    var hiltRule = HiltAndroidRule(this)

    @get:Rule(order = 1)
    val composeTestRule = createAndroidComposeRule<MainActivity>()

    @Before
    fun setUp() {
        hiltRule.inject()
    }

    @Test
    fun app_launches_successfully() {
        // Just checking if the app launches without crashing
        // Since we don't know the exact text on the home screen immediately,
        // we can simply wait for idle which means the main screen rendered.
        composeTestRule.waitForIdle()
    }
}
